import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { faqKnowledgeBaseSchema } from "../src/validators/faq.schema.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const kbPath = path.resolve(__dirname, "../kb/faqs.json");
const outputDocPath = path.resolve(__dirname, "../../docs/college-faqs.md");

console.log("==================================================");
console.log("📄 Generating College FAQs Documentation Markdown...");
console.log(`📁 Source KB: ${kbPath}`);
console.log(`📁 Destination: ${outputDocPath}`);

try {
  if (!fs.existsSync(kbPath)) {
    console.error(`❌ Error: Knowledge base file not found at ${kbPath}`);
    process.exit(1);
  }

  const rawData = fs.readFileSync(kbPath, "utf-8");
  const json = JSON.parse(rawData);

  const validation = faqKnowledgeBaseSchema.safeParse(json);
  if (!validation.success) {
    console.error("❌ Cannot generate documentation from invalid knowledge base data!");
    console.error(validation.error.format());
    process.exit(1);
  }

  const { metadata, faqs } = validation.data;

  // Group FAQs by category
  const categories = {};
  for (const faq of faqs) {
    if (!categories[faq.category]) {
      categories[faq.category] = [];
    }
    categories[faq.category].push(faq);
  }

  // Construct Markdown
  let markdown = `# ${metadata.title}\n\n`;
  markdown += `> **DISCLAIMER:** ${metadata.disclaimer}\n\n`;
  markdown += `**Institution Department:** ${metadata.department || "Department of Computer Science & Engineering"}\n`;
  markdown += `**Dataset Type:** \`${metadata.dataType}\` (Verified: \`${metadata.verified}\`)\n`;
  markdown += `**Version:** ${metadata.version || "1.0.0"}\n`;
  markdown += `**Total Documented FAQs:** ${faqs.length}\n`;
  markdown += `**Last Generated:** ${new Date().toISOString()}\n\n`;
  markdown += `---\n\n`;

  markdown += `## 📑 Table of Contents\n\n`;
  for (const cat of Object.keys(categories)) {
    const slug = cat.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    markdown += `- [${cat} (${categories[cat].length} entries)](#${slug})\n`;
  }
  markdown += `\n---\n\n`;

  for (const [categoryName, items] of Object.entries(categories)) {
    markdown += `## ${categoryName}\n\n`;
    for (const item of items) {
      markdown += `### \`[${item.id}]\` ${item.question}\n\n`;
      markdown += `**Answer:**\n${item.answer}\n\n`;
      markdown += `**Keywords:** ${item.keywords.map(k => `\`${k}\``).join(", ")}\n\n`;
      markdown += `---\n\n`;
    }
  }

  markdown += `\n*Note: This document is auto-generated by \`npm run generate:faq-doc\` from \`server/kb/faqs.json\`. Do not edit this markdown file manually.*\n`;

  const outputDir = path.dirname(outputDocPath);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(outputDocPath, markdown, "utf-8");
  console.log(`✅ Successfully generated ${outputDocPath} with ${faqs.length} FAQs across ${Object.keys(categories).length} categories.`);
  console.log("==================================================");
  process.exit(0);
} catch (err) {
  console.error("❌ Unexpected error during document generation:", err.message);
  process.exit(1);
}
